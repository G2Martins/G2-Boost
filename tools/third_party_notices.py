"""Generate THIRD_PARTY_NOTICES.md for the shipped app.

Rust: every crate linked into the Windows build of `g2-boost` (`cargo tree -e normal`).
JS: every production dependency bundled into the webview (package.json "dependencies", transitively).
License texts are copied from each package's own LICENSE/COPYING/NOTICE files and de-duplicated.

Run from the repo root before each release:  python -I tools/third_party_notices.py
"""

import glob
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LICENSE_RE = re.compile(r"^(licen[cs]e|copying|notice|unlicense)([-_.].*)?$", re.I)


def cargo_home():
    return os.environ.get("CARGO_HOME") or os.path.join(os.path.expanduser("~"), ".cargo")


def license_files(directory):
    out = []
    try:
        names = sorted(os.listdir(directory))
    except OSError:
        return out
    for n in names:
        p = os.path.join(directory, n)
        if os.path.isfile(p) and LICENSE_RE.match(n):
            with open(p, encoding="utf-8", errors="replace") as f:
                out.append((n, f.read().strip()))
    return out


def rust_packages():
    cmd = [
        "cargo", "tree", "-p", "g2-boost", "-e", "normal", "--target", "x86_64-pc-windows-msvc",
        "--prefix", "none", "--format", "{p}|{l}",
    ]
    lines = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=True).stdout.splitlines()
    registry = glob.glob(os.path.join(cargo_home(), "registry", "src", "index.crates.io-*"))
    pkgs = {}
    for line in lines:
        line = line.replace(" (*)", "").strip()
        if not line or "|" not in line:
            continue
        spec, lic = line.split("|", 1)
        parts = spec.split()
        name, version = parts[0], parts[1].lstrip("v")
        if len(parts) > 2:  # path dependency = our own crates / local stub
            continue
        d = next((os.path.join(r, f"{name}-{version}") for r in registry if os.path.isdir(os.path.join(r, f"{name}-{version}"))), None)
        pkgs[(name, version)] = (lic or "see license file", license_files(d) if d else [])
    return pkgs


def js_packages():
    nm = os.path.join(ROOT, "node_modules")
    with open(os.path.join(ROOT, "package.json"), encoding="utf-8") as f:
        todo = list(json.load(f).get("dependencies", {}))
    seen, pkgs = set(), {}
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        seen.add(name)
        d = os.path.join(nm, *name.split("/"))
        pj = os.path.join(d, "package.json")
        if not os.path.isfile(pj):
            continue  # optional/platform dependency not installed
        with open(pj, encoding="utf-8") as f:
            meta = json.load(f)
        lic = meta.get("license")
        if isinstance(lic, dict):
            lic = lic.get("type")
        pkgs[(name, meta.get("version", "?"))] = (lic or "see license file", license_files(d))
        todo.extend(meta.get("dependencies", {}))
    return pkgs


def main():
    rust, js = rust_packages(), js_packages()
    texts = {}  # sha -> (text, [package labels])
    for eco, pkgs in (("rust", rust), ("npm", js)):
        for (name, version), (_lic, files) in pkgs.items():
            for _fname, text in files:
                sha = hashlib.sha256(text.encode()).hexdigest()[:16]
                texts.setdefault(sha, (text, []))[1].append(f"{name} {version}")

    out = [
        "# Third-party notices — G2 Boost",
        "",
        "G2 Boost is proprietary software (see LICENSE). It includes the open-source components below,",
        "each under its own license. Nothing in the G2 Boost license limits the rights those licenses grant.",
        "Generated by `tools/third_party_notices.py`; regenerate before every release.",
        "",
        f"## Rust crates ({len(rust)})",
        "",
        "| Crate | Version | License |",
        "|---|---|---|",
    ]
    out += [f"| {n} | {v} | {lic} |" for (n, v), (lic, _f) in sorted(rust.items())]
    out += ["", f"## JavaScript packages bundled in the UI ({len(js)})", "", "| Package | Version | License |", "|---|---|---|"]
    out += [f"| {n} | {v} | {lic} |" for (n, v), (lic, _f) in sorted(js.items())]
    out += ["", "## License texts", ""]
    for _sha, (text, users) in sorted(texts.items(), key=lambda kv: sorted(kv[1][1])[0]):
        out += [f"### {', '.join(sorted(users))}", "", "```text", text.replace("```", "'''"), "```", ""]
    missing = [f"{n} {v}" for pkgs in (rust, js) for (n, v), (_l, f) in pkgs.items() if not f]
    if missing:
        out += ["## Packages without a bundled license file", "",
                "Covered by the SPDX license declared in the tables above:", "", ", ".join(sorted(missing)), ""]
    path = os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {path}: {len(rust)} crates, {len(js)} npm packages, {len(texts)} distinct license texts, {len(missing)} without file")


if __name__ == "__main__":
    sys.exit(main())
